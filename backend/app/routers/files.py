import base64
import httpx
from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import Response, PlainTextResponse
from pydantic import BaseModel

from ..auth import get_current_user, AuthenticatedUser
from ..config import settings
from ..pipeline.file_writer import file_writer

router = APIRouter(prefix="/api/projects", tags=["Project Files"])


class GitHubPushRequest(BaseModel):
    owner: str
    repo: str
    branch: str = "main"
    token: str | None = None
    commit_message: str = "feat: generated by AI Software Team Studio"


@router.get("/{project_id}/tree")
async def get_project_file_tree(
    project_id: str,
    user: AuthenticatedUser = Depends(get_current_user)
):
    """Returns the file and folder hierarchy generated by the AI software team."""
    tree = file_writer.list_project_tree(project_id)
    return {"project_id": project_id, "files": tree}


@router.get("/{project_id}/file")
async def get_file_content(
    project_id: str,
    path: str = Query(..., description="Relative file path, e.g. src/App.tsx"),
    user: AuthenticatedUser = Depends(get_current_user)
):
    """Reads the content of a specific generated code file."""
    try:
        safe_path = file_writer._sanitize_path(project_id, path)
        if not safe_path.exists() or not safe_path.is_file():
            raise HTTPException(status_code=404, detail="File not found")
        content = safe_path.read_text(encoding="utf-8")
        return PlainTextResponse(content)
    except ValueError as ve:
        raise HTTPException(status_code=400, detail=str(ve))


@router.get("/{project_id}/download")
async def download_project_zip(
    project_id: str,
    user: AuthenticatedUser = Depends(get_current_user)
):
    """Downloads the full generated project workspace as a ready-to-run ZIP archive."""
    try:
        zip_bytes = file_writer.create_zip_archive(project_id)
        return Response(
            content=zip_bytes,
            media_type="application/zip",
            headers={"Content-Disposition": f"attachment; filename=project_{project_id[:8]}.zip"}
        )
    except FileNotFoundError:
        raise HTTPException(status_code=404, detail="Project workspace not found.")


@router.post("/{project_id}/push-github")
async def push_project_to_github(
    project_id: str,
    req: GitHubPushRequest,
    user: AuthenticatedUser = Depends(get_current_user)
):
    """
    Pushes all generated project files directly to a GitHub repository via GitHub Contents API.
    """
    gh_token = req.token or settings.GITHUB_TOKEN
    if not gh_token:
        raise HTTPException(
            status_code=400,
            detail={"error": {"code": "MISSING_GITHUB_TOKEN", "message": "Provide a GitHub Personal Access Token or configure GITHUB_TOKEN in backend/.env"}}
        )

    files = file_writer.list_project_tree(project_id)
    if not files:
        raise HTTPException(status_code=404, detail="No generated files found for this project")

    headers = {
        "Authorization": f"Bearer {gh_token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28"
    }

    pushed_files = []
    async with httpx.AsyncClient(timeout=30.0) as client:
        for item in files:
            rel_path = item["path"]
            safe_path = file_writer._sanitize_path(project_id, rel_path)
            raw_bytes = safe_path.read_bytes()
            encoded = base64.b64encode(raw_bytes).decode("ascii")

            url = f"https://api.github.com/repos/{req.owner}/{req.repo}/contents/{rel_path}"

            # Check existing SHA so updates work cleanly
            existing_sha = None
            get_res = await client.get(url, headers=headers, params={"ref": req.branch})
            if get_res.status_code == 200:
                existing_sha = get_res.json().get("sha")

            body = {
                "message": f"{req.commit_message} ({rel_path})",
                "content": encoded,
                "branch": req.branch,
            }
            if existing_sha:
                body["sha"] = existing_sha

            put_res = await client.put(url, headers=headers, json=body)
            if put_res.status_code not in (200, 201):
                raise HTTPException(
                    status_code=put_res.status_code,
                    detail={"error": {"code": "GITHUB_PUSH_FAILED", "message": f"Failed on {rel_path}: {put_res.text}"}}
                )
            pushed_files.append(rel_path)

    return {
        "status": "ok",
        "repository": f"{req.owner}/{req.repo}",
        "branch": req.branch,
        "pushed_count": len(pushed_files),
        "pushed_files": pushed_files,
    }
